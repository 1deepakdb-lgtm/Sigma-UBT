def clean_word(k):
    if not k:
        return ""
    k = re.sub(r'[\(\[\{].*?[\)\]\}]', '', k).strip()
    k = re.sub(r'C\s*H\s*A\s*P\s*T\s*E\s*R.*', '', k, flags=re.I).strip()
    k = re.sub(r'GRAMMAR.*', '', k, flags=re.I).strip()
    k = re.sub(r'제\d+과\s*핵심어휘\s*\d*', '', k).strip()
    return k

def get_clean_nepali(korean, existing_nepali=""):
    ck = clean_word(korean)
    if ck in FULL_DICT:
        return FULL_DICT[ck]
    if korean in FULL_DICT:
        return FULL_DICT[korean]
    
    # If existing has devanagari and is not dummy
    if existing_nepali and re.search(r'[\u0900-\u097F]', existing_nepali):
        if 'महत्त्वपूर्ण शब्दावली' not in existing_nepali and 'शब्दावली' != existing_nepali.strip():
            return existing_nepali.strip()
    
    # Generic fallback based on clean word
    return f"{ck} (शब्दावली)"
