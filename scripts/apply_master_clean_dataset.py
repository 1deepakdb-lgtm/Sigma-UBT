def clean_korean(k):
    k = re.sub(r'[\(\[\{].*?[\)\]\}]', '', k).strip()
    k = re.sub(r'C\s*H\s*A\s*P\s*T\s*E\s*R.*', '', k, flags=re.I).strip()
    k = re.sub(r'GRAMMAR.*', '', k, flags=re.I).strip()
    k = re.sub(r'제\d+과\s*핵심어휘\s*\d*', '', k).strip()
    k = re.sub(r'Tips for.*', '', k, flags=re.I).strip()
    return k

def is_garbage(k, n):
    if not k or len(k) < 1:
        return True
    if any(x in k for x in ['핵심어휘', 'C H A P T E R', 'GRAMMAR', 'VOCA', '과제', '활동', '  ']):
        return True
    if any(x in n for x in ['핵심어휘', 'महत्त्वपूर्ण शब्दावली', 'C H A P T E R', 'GRAMMAR', 'Tips for']):
        return True
    # Discard reading sentence fragments
    if k in ['저는', '저도', '한국에는', '그래서 직장인들은', '그럼', '닛차난 씨는', '닛차난 씨도', '마두 씨', '원이고']:
        return True
    return False

def translate(k, raw_n):
    ck = clean_korean(k)
    if ck in SUPREME_MAP:
        return SUPREME_MAP[ck]
    if k in SUPREME_MAP:
        return SUPREME_MAP[k]
    # Check if raw_n is clean devanagari
    if raw_n and re.search(r'[\u0900-\u097F]', raw_n) and not re.search(r'^[A-Za-z0-9\s.,\-\/\(\)]+$', raw_n):
        if 'महत्त्वपूर्ण शब्दावली' not in raw_n:
            return raw_n.strip()
    return ""

