    k = re.sub(r'[\(\[\{].*?[\)\]\}]', '', k)
    k = re.sub(r'C\s*H\s*A\s*P\s*T\s*E\s*R.*', '', k, flags=re.I)
    k = re.sub(r'GRAMMAR.*', '', k, flags=re.I)
