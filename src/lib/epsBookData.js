/**
 * Storage Key for 60 Chapters
 */
export const EPS_60_STORAGE_KEY = "eps60Chapters";

/**
 * Load all 60 chapters from localStorage, or populate with defaults
 */
export function loadEps60Chapters() {
  if (typeof window === "undefined") return INITIAL_60_CHAPTERS;
  try {
    const raw = localStorage.getItem(EPS_60_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(EPS_60_STORAGE_KEY, JSON.stringify(INITIAL_60_CHAPTERS));
      return INITIAL_60_CHAPTERS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(EPS_60_STORAGE_KEY, JSON.stringify(INITIAL_60_CHAPTERS));
      return INITIAL_60_CHAPTERS;
    }
    // Update existing stored items if they lack coverImage or have old titles
    const chMap = new Map();
    INITIAL_60_CHAPTERS.forEach(init => chMap.set(init.chapter, init));
    const merged = parsed.map(p => {
      const init = chMap.get(p.chapter);
      if (!init) return p;
      return {
        ...init,
        ...p,
        titleKo: init.titleKo,
        titleNe: init.titleNe,
        pdfUrl: init.pdfUrl,
        coverImage: init.coverImage,
        audioTracks: (p.audioTracks && p.audioTracks.length > 0) ? p.audioTracks : init.audioTracks
      };
    });
    localStorage.setItem(EPS_60_STORAGE_KEY, JSON.stringify(merged));
    return merged;
  } catch (err) {
    console.error("Error loading EPS 60 chapters:", err);
    return INITIAL_60_CHAPTERS;
  }
}

/**
 * Save updated chapters list
 */
export function saveEps60Chapters(chapters) {
  if (typeof window === "undefined") return;
  try {
    localStorage.setItem(EPS_60_STORAGE_KEY, JSON.stringify(chapters));
  } catch (err) {
    console.error("Error saving EPS 60 chapters:", err);
  }
}

/**
 * Update single chapter in localStorage
 */
export function updateEpsChapter(chapterNumber, updatedFields) {
  const list = loadEps60Chapters();
  const updated = list.map((item) => {
    if (item.chapter === Number(chapterNumber)) {
      return { ...item, ...updatedFields };
    }
    return item;
  });
  saveEps60Chapters(updated);
  return updated;
}

/**
 * Fetch server-persisted chapters for real-time synchronization across all users (students, institutes, admin)
 */
export async function fetchServerEpsChapters() {
  try {
    const res = await fetch('/api/eps-book', { cache: 'no-store' });
    if (!res.ok) return null;
    const data = await res.json();
    if (data.success && Array.isArray(data.chapters) && data.chapters.length > 0) {
      saveEps60Chapters(data.chapters);
      return data.chapters;
    }
  } catch (err) {
    console.warn('Error loading EPS chapters from server:', err);
  }
  return null;
}

/**
 * Persist chapter changes to server storage so all students and institutes see them
 */
export async function syncChapterToServer(chapterNumber, updatedFields) {
  try {
    const res = await fetch('/api/eps-book', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-user-role': 'admin'
      },
      credentials: 'include',
      body: JSON.stringify({
        chapter: Number(chapterNumber),
        ...updatedFields
      })
    });
    const data = await res.json();
    if (data.success && Array.isArray(data.chapters)) {
      saveEps60Chapters(data.chapters);
      return data.chapters;
    }
  } catch (err) {
    console.warn('Error syncing chapter to server:', err);
  }
  return null;
}
